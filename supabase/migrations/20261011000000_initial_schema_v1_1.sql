create or replace function public.validar_voto()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  propietario uuid;
begin
  if new.publicacion_id is not null then
    select autor_id into propietario from public.publicaciones where id = new.publicacion_id;
  else
    select autor_id into propietario from public.comentarios where id = new.comentario_id;
  end if;

  if propietario is null then
    raise exception 'El contenido votado no existe';
  end if;
  if propietario = new.usuario_id then
    raise exception 'No puedes votar tu propio contenido';
  end if;
  return new;
end;
$$;

create trigger votos_validar_propietario before insert or update on public.votos
  for each row execute function public.validar_voto();

create or replace function public.validar_reporte_duplicado_pendiente()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1
    from public.reportes r
    where r.reportante_id = new.reportante_id
      and r.estado_id = public.id_maestra('estado_reporte', 'pendiente')
      and r.id <> coalesce(new.id, gen_random_uuid())
      and (
        (new.publicacion_id is not null and r.publicacion_id = new.publicacion_id)
        or (new.comentario_id is not null and r.comentario_id = new.comentario_id)
      )
  ) then
    raise exception 'Ya existe un reporte pendiente para este contenido';
  end if;
  return new;
end;
$$;

create trigger reportes_evitar_duplicado_pendiente before insert on public.reportes
  for each row execute function public.validar_reporte_duplicado_pendiente();

create or replace function public.otorgar_puntos(
  p_usuario_id uuid,
  p_motivo_codigo text,
  p_puntos integer,
  p_clave_unica text,
  p_publicacion_id uuid default null,
  p_maximo_diario integer default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_motivo_id integer;
  v_filas_insertadas integer;
begin
  v_motivo_id := public.id_maestra('motivo_puntos', p_motivo_codigo);
  if v_motivo_id is null then
    raise exception 'Motivo de puntos no configurado: %', p_motivo_codigo;
  end if;

  if p_maximo_diario is not null and (
    select count(*)
    from public.eventos_puntos
    where usuario_id = p_usuario_id
      and motivo_id = v_motivo_id
      and creado_en >= date_trunc('day', now())
  ) >= p_maximo_diario then
    return false;
  end if;

  insert into public.eventos_puntos (usuario_id, motivo_id, puntos, publicacion_id, clave_unica)
  values (p_usuario_id, v_motivo_id, p_puntos, p_publicacion_id, p_clave_unica)
  on conflict (clave_unica) do nothing;

  get diagnostics v_filas_insertadas = row_count;
  if v_filas_insertadas > 0 then
    update public.perfiles
    set puntos = puntos + p_puntos
    where id = p_usuario_id;
  end if;
  return v_filas_insertadas > 0;
end;
$$;

