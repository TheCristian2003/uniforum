create extension if not exists pgcrypto;

create table public.maestra (
  id_maestra integer generated by default as identity primary key,
  grupo varchar(50) not null,
  codigo varchar(50) not null,
  nombre varchar(100) not null,
  descripcion varchar(255),
  padre_id integer references public.maestra(id_maestra) on delete restrict,
  activo boolean not null default true,
  orden integer not null default 0,
  constraint maestra_grupo_codigo_key unique (grupo, codigo)
);

create table public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  alias varchar(50) not null unique,
  tipo_perfil_id integer not null references public.maestra(id_maestra) on delete restrict,
  programa_id integer references public.maestra(id_maestra) on delete set null,
  sede_id integer references public.maestra(id_maestra) on delete set null,
  biografia varchar(255),
  avatar_url varchar(500),
  es_verificada boolean not null default false,
  nombre_oficial varchar(100),
  puntos integer not null default 0 check (puntos >= 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint perfiles_alias_no_vacio check (char_length(btrim(alias)) between 3 and 50)
);

create table public.canales (
  id uuid primary key default gen_random_uuid(),
  nombre varchar(100) not null,
  slug varchar(100) not null unique,
  descripcion varchar(255),
  tipo_canal_id integer not null references public.maestra(id_maestra) on delete restrict,
  unidad_id integer references public.maestra(id_maestra) on delete set null,
  icono varchar(100),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint canales_nombre_no_vacio check (char_length(btrim(nombre)) between 2 and 100),
  constraint canales_slug_formato check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create table public.publicaciones (
  id uuid primary key default gen_random_uuid(),
  canal_id uuid not null references public.canales(id) on delete restrict,
  autor_id uuid not null default auth.uid() references public.perfiles(id) on delete restrict,
  tipo_id integer not null references public.maestra(id_maestra) on delete restrict,
  categoria_id integer not null references public.maestra(id_maestra) on delete restrict,
  estado_id integer not null references public.maestra(id_maestra) on delete restrict,
  titulo varchar(200),
  cuerpo text not null,
  imagenes text[] not null default '{}',
  metadatos jsonb not null default '{}'::jsonb,
  anonimo boolean not null default false,
  puntaje integer not null default 0,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint publicaciones_cuerpo_no_vacio check (char_length(btrim(cuerpo)) > 0),
  constraint publicaciones_titulo_no_vacio check (titulo is null or char_length(btrim(titulo)) > 0),
  constraint publicaciones_metadatos_objeto check (jsonb_typeof(metadatos) = 'object')
);

create table public.comentarios (
  id uuid primary key default gen_random_uuid(),
  publicacion_id uuid not null references public.publicaciones(id) on delete cascade,
  autor_id uuid not null default auth.uid() references public.perfiles(id) on delete restrict,
  cuerpo text not null,
  es_solucion boolean not null default false,
  puntaje integer not null default 0,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint comentarios_cuerpo_no_vacio check (char_length(btrim(cuerpo)) > 0)
);

create table public.votos (
  id uuid primary key default gen_random_uuid(),
  publicacion_id uuid references public.publicaciones(id) on delete cascade,
  usuario_id uuid not null default auth.uid() references public.perfiles(id) on delete cascade,
  comentario_id uuid references public.comentarios(id) on delete cascade,
  valor integer not null check (valor in (1, -1)),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint votos_un_objetivo check (
    (publicacion_id is not null and comentario_id is null)
    or (publicacion_id is null and comentario_id is not null)
  )
);

create unique index votos_un_usuario_publicacion_idx
  on public.votos(usuario_id, publicacion_id)
  where publicacion_id is not null;

create unique index votos_un_usuario_comentario_idx
  on public.votos(usuario_id, comentario_id)
  where comentario_id is not null;

create table public.reportes (
  id uuid primary key default gen_random_uuid(),
  publicacion_id uuid references public.publicaciones(id) on delete cascade,
  comentario_id uuid references public.comentarios(id) on delete cascade,
  reportante_id uuid not null default auth.uid() references public.perfiles(id) on delete restrict,
  motivo_id integer not null references public.maestra(id_maestra) on delete restrict,
  descripcion varchar(500),
  estado_id integer not null references public.maestra(id_maestra) on delete restrict,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint reportes_un_objetivo check (
    (publicacion_id is not null and comentario_id is null)
    or (publicacion_id is null and comentario_id is not null)
  )
);

create table public.eventos_puntos (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null references public.perfiles(id) on delete cascade,
  motivo_id integer not null references public.maestra(id_maestra) on delete restrict,
