create or replace function public.actualizar_puntaje_y_puntos_voto()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_delta integer;
  v_autor_id uuid;
  v_publicacion_id uuid;
  v_comentario_id uuid;
  v_voto_id uuid;
begin
  if tg_op = 'INSERT' then
    v_delta := new.valor;
    v_publicacion_id := new.publicacion_id;
    v_comentario_id := new.comentario_id;
    v_voto_id := new.id;
  elsif tg_op = 'UPDATE' then
    v_delta := new.valor - old.valor;
    v_publicacion_id := new.publicacion_id;
    v_comentario_id := new.comentario_id;
    v_voto_id := new.id;
  else
    v_delta := -old.valor;
    v_publicacion_id := old.publicacion_id;
    v_comentario_id := old.comentario_id;
    v_voto_id := old.id;
  end if;

  if v_publicacion_id is not null then
    update public.publicaciones set puntaje = puntaje + v_delta where id = v_publicacion_id returning autor_id into v_autor_id;
    if tg_op <> 'DELETE' and new.valor = 1 then
      perform public.otorgar_puntos(v_autor_id, 'voto_positivo_publicacion', 3, 'voto_publicacion:' || v_voto_id, v_publicacion_id, null);
    end if;
  else
    select c.autor_id, c.publicacion_id into v_autor_id, v_publicacion_id
    from public.comentarios c where c.id = v_comentario_id;
    update public.comentarios set puntaje = puntaje + v_delta where id = v_comentario_id;
    if tg_op <> 'DELETE' and new.valor = 1 then
      perform public.otorgar_puntos(v_autor_id, 'voto_positivo_comentario', 2, 'voto_comentario:' || v_voto_id, v_publicacion_id, null);
    end if;
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

