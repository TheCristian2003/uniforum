create or replace function public.id_maestra(p_grupo text, p_codigo text)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select id_maestra
  from public.maestra
  where grupo = p_grupo and codigo = p_codigo and activo
$$;

create or replace function public.validar_catalogos()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_table_name = 'perfiles' then
    if not exists (select 1 from public.maestra where id_maestra = new.tipo_perfil_id and grupo = 'tipo_perfil' and activo) then
      raise exception 'tipo_perfil_id debe pertenecer al grupo tipo_perfil';
    end if;
    if new.programa_id is not null and not exists (select 1 from public.maestra where id_maestra = new.programa_id and grupo = 'programa' and activo) then
      raise exception 'programa_id debe pertenecer al grupo programa';
    end if;
    if new.sede_id is not null and not exists (select 1 from public.maestra where id_maestra = new.sede_id and grupo = 'sede' and activo) then
      raise exception 'sede_id debe pertenecer al grupo sede';
    end if;
  elsif tg_table_name = 'canales' then
    if not exists (select 1 from public.maestra where id_maestra = new.tipo_canal_id and grupo = 'tipo_canal' and activo) then
      raise exception 'tipo_canal_id debe pertenecer al grupo tipo_canal';
    end if;
    if new.unidad_id is not null and not exists (select 1 from public.maestra where id_maestra = new.unidad_id and grupo in ('facultad', 'programa', 'sede') and activo) then
      raise exception 'unidad_id debe pertenecer a facultad, programa o sede';
    end if;
  elsif tg_table_name = 'publicaciones' then
    if not exists (select 1 from public.maestra where id_maestra = new.tipo_id and grupo = 'tipo_publicacion' and activo) then
      raise exception 'tipo_id debe pertenecer al grupo tipo_publicacion';
    end if;
    if not exists (select 1 from public.maestra where id_maestra = new.categoria_id and grupo = 'categoria_publicacion' and activo) then
      raise exception 'categoria_id debe pertenecer al grupo categoria_publicacion';
    end if;
    if not exists (select 1 from public.maestra where id_maestra = new.estado_id and grupo = 'estado_publicacion' and activo) then
      raise exception 'estado_id debe pertenecer al grupo estado_publicacion';
    end if;
  elsif tg_table_name = 'reportes' then
    if not exists (select 1 from public.maestra where id_maestra = new.motivo_id and grupo = 'motivo_reporte' and activo) then
      raise exception 'motivo_id debe pertenecer al grupo motivo_reporte';
    end if;
    if not exists (select 1 from public.maestra where id_maestra = new.estado_id and grupo = 'estado_reporte' and activo) then
      raise exception 'estado_id debe pertenecer al grupo estado_reporte';
    end if;
  elsif tg_table_name = 'eventos_puntos' then
    if not exists (select 1 from public.maestra where id_maestra = new.motivo_id and grupo = 'motivo_puntos' and activo) then
      raise exception 'motivo_id debe pertenecer al grupo motivo_puntos';
    end if;
  end if;
  return new;
end;
$$;

