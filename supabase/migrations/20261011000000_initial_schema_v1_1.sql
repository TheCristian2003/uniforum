create or replace function public.marcar_comentario_solucion(p_comentario_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_autor_publicacion uuid;
  v_autor_comentario uuid;
  v_publicacion_id uuid;
begin
  select p.autor_id, c.autor_id, c.publicacion_id
    into v_autor_publicacion, v_autor_comentario, v_publicacion_id
  from public.comentarios c
  join public.publicaciones p on p.id = c.publicacion_id
  where c.id = p_comentario_id;

  if v_autor_publicacion is null then
    raise exception 'Comentario no encontrado';
  end if;
  if v_autor_publicacion <> auth.uid() then
    raise exception 'Solo el autor de la publicación puede marcar una solución';
  end if;

  update public.comentarios set es_solucion = true where id = p_comentario_id and not es_solucion;
  if found then
    perform public.otorgar_puntos(v_autor_comentario, 'comentario_solucion', 15, 'solucion:' || p_comentario_id, v_publicacion_id, null);
  end if;
end;
$$;

